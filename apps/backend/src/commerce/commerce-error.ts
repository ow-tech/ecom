import { ConflictException } from "@nestjs/common";

export type CommerceConflictCode = "PRICE_CHANGED" | "INSUFFICIENT_STOCK" | "LISTING_UNAVAILABLE" | "CART_CURRENCY_MISMATCH" | "CHECKOUT_ALREADY_TERMINAL" | "ORDER_NOT_PAYABLE" | "PAYMENT_REFERENCE_MISMATCH" | "PAYMENT_AMOUNT_MISMATCH" | "PAYMENT_CURRENCY_MISMATCH" | "PAYMENT_CUSTOMER_MISMATCH" | "PAYMENT_CHANNEL_MISMATCH" | "PAYMENT_METHOD_MISMATCH" | "PAYMENT_METHOD_UNAVAILABLE" | "DELIVERY_QUOTE_NOT_PENDING" | "DELIVERY_QUOTE_NOT_QUOTED" | "DELIVERY_QUOTE_EXPIRED" | "DELIVERY_QUOTE_CURRENCY_MISMATCH" | "PAYMENT_AMOUNT_BOUND";

export function commerceConflict(code: CommerceConflictCode, message: string): ConflictException {
  return new ConflictException({ statusCode: 409, error: "Conflict", code, message });
}
